/** Owner-only UI action: explicitly select the local HoHo Manager repository folder. */
export const writeDesignFilesToLocalProject = async (
  puckData: unknown,
  themeValue: UiThemeTokens,
): Promise<void> => {
  const picker = (window as unknown as DirectoryPickerWindow).showDirectoryPicker;
  if (!picker) {
    throw new Error("Folder access is unavailable in this browser. Open Design Lab in Chrome or Edge.");
  }

  const root = await picker();
  const client = await root.getDirectoryHandle("client");
  const src = await client.getDirectoryHandle("src");
  const config = await src.getDirectoryHandle("config");
  const puck = await config.getDirectoryHandle("puck");
  const theme = normalizeUiTheme(themeValue);

  await writeFile(
    puck,
    "publishedDesign.ts",
    "/** Generated by HoHo Design Lab. Owner-published Puck document. */\nexport const publishedDesign: unknown = " +
      JSON.stringify(puckData, null, 2) + ";\n",
  );
  await writeFile(
    puck,
    "publishedTheme.ts",
    'import type { UiThemeTokens } from "../../utils/puckTheme";\n\nexport const publishedThemeTokens: UiThemeTokens = ' +
      JSON.stringify(theme, null, 2) + ";\n",
  );
  await writeFile(puck, "publishedTheme.css", themeCss(theme));
};
