import type { UiThemeTokens } from "./puckTheme";
import { normalizeUiTheme } from "./puckTheme";

interface WritableFile { write(data: string): Promise<void>; close(): Promise<void>; }
interface FileHandle { createWritable(): Promise<WritableFile>; }
interface DirectoryHandle {
  getDirectoryHandle(name: string, options?: { create?: boolean }): Promise<DirectoryHandle>;
  getFileHandle(name: string, options?: { create?: boolean }): Promise<FileHandle>;
}
type DirectoryPickerWindow = { showDirectoryPicker?: () => Promise<DirectoryHandle> };

const writeFile = async (directory: DirectoryHandle, name: string, content: string): Promise<void> => {
  const handle = await directory.getFileHandle(name, { create: true });
  const writable = await handle.createWritable();
  await writable.write(content);
  await writable.close();
};

