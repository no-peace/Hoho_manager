export const UNICODE_EMOJI_LIST: UnicodeEmojiItem[] = Object.entries(UNICODE_EMOJI_CATEGORIES).flatMap(
  ([category, items]) =>
    items.map((item) => ({
      name: item.name,
      char: item.char,
      category,
      keywords: [item.name.replace(/_/g, " ")],
    }))
);

export function searchUnicodeEmojis(query: string, limit = 20): UnicodeEmojiItem[] {
  const q = query.toLowerCase().trim().replace(/^:|:$/g, "");
  if (!q) return UNICODE_EMOJI_LIST.slice(0, limit);
  return UNICODE_EMOJI_LIST.filter(
    (e) =>
      e.name.toLowerCase().includes(q) ||
      e.char.includes(q) ||
      e.keywords.some((k) => k.toLowerCase().includes(q))
  ).slice(0, limit);
}

